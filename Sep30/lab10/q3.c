#include <stdio.h>

int main() {
    long int a, b, product;

    printf("Enter two numbers: ");
    // Read the two long integers
    scanf("%ld %ld", &a, &b);

    // Calculate their product
    product = a * b;

    printf("The product is %ld\n", product);

    return 0;
}
